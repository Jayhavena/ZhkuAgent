package com.zhku.knowledge.routing;

/**
 * 规则目录项的风险等级。
 *
 * <p>只有 {@link #HIGH} 级规则允许在路由第三级直接给出结论；
 * 中低风险规则即使命中也必须回落到检索增强级，由获准证据支撑表述，
 * 防止影响面小的细则被误当成可独立作答的依据。</p>
 */
public enum RuleRisk {

    /** 直接影响学生学业结论（如缓考、重修、退学边界），必须命中已发布规则原文才可作答。 */
    HIGH,

    /** 一般办理细则，需要证据支撑但允许检索增强级表述。 */
    MEDIUM,

    /** 参考性说明，不单独构成回答依据。 */
    LOW
}
